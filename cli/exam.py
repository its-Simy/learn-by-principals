app = typer.Typer(no_args_is_help=True, help="Practice exams.")
console = Console()

TAKE_HELP = (
    "Answer each question; multiple choice by letter. Coding answers end with a line /done. "
    "/skip skips a question, /quit saves and stops (take it again to resume)."
)


@app.command("create")
def create(
    spec_path: Path = typer.Option(
        ..., "--spec", exists=True, dir_okay=False, help="The ExamSpec YAML."
    ),
) -> None:
    """Plan, generate and critique an exam; writes its .json and .md to the vault."""
    try:
        spec = load_spec(spec_path)
    except SpecError as exc:
        raise typer.BadParameter(str(exc)) from exc
    config = load_config()
    conn = connect(config.db_path)
    try:
        # Grounding queries start fresh conversations, which would end a live tutor's (P66).
        refuse_if_session_open(conn, spec.course)
        learner = LearnerMemory(conn)
        concepts = learner.concepts(spec.course)
        mastery = {c.concept_id: m for c in concepts if (m := learner.get_mastery(c.concept_id))}
        try:
            coverage = plan(spec, concepts, mastery)
        except PlanError as exc:
            console.print(f"[red]{escape(str(exc))}[/]")
            raise typer.Exit(1) from exc
        _print_plan_notes(coverage)
        providers = common.model_providers(config, ("teaching", "analysis"))
        router = common.router(config, conn, providers)
        manifest = Manifest(conn)
        with common.open_knowledge(config, conn) as knowledge:
            generator = QuestionGenerator(
                router, router, ContextCompiler(knowledge, learner, manifest), manifest
            )
            try:
                report = generator.generate(coverage)
            except GenerationError as exc:
                console.print(f"[red]{escape(str(exc))}[/]")
                raise typer.Exit(1) from exc
    finally:
        conn.close()
    if not report.questions:
        console.print("[red]No valid questions were generated; nothing written.[/]")
        raise typer.Exit(1)
    json_path, md_path = new_paths(config.vault_root, spec.course, spec.slug, datetime.now())
    exam = new_exam(json_path.stem, coverage, report)
    save(json_path, exam)
    md_path.write_text(to_markdown(exam))

    console.print(
        f"[green]{len(report.questions)}[/] of {coverage.total} questions · generated by "
        f"{', '.join(report.generator_providers)} · critic "
        f"{report.critic_provider or 'skipped'} · {len(report.regenerated)} rewritten"
    )
    for reason in report.dropped:
        console.print(f"[yellow]Dropped: {escape(reason)}[/]")
    if not report.critiqued:
        reason = report.critique_skipped or "no critic"
        console.print(f"[yellow]Uncritiqued: {escape(reason)}[/]")
    console.print(f"{json_path}\n{md_path}")


def _print_plan_notes(coverage) -> None:
    if coverage.no_week:
        console.print(
            f"[yellow]{len(coverage.no_week)} concept(s) have no week and were left out; "
            "re-run `brightlearn concepts apply` to fill weeks in.[/]"
        )
    for name in coverage.unmatched_include:
        console.print(f"[yellow]include: no concept matches {escape(name)!r}[/]")
    for name in coverage.unmatched_exclude:
        console.print(f"[yellow]exclude: no concept matches {escape(name)!r}[/]")


@app.command("take")
def take(
    file: Path = typer.Argument(..., exists=True, dir_okay=False, help="The exam's .json."),
) -> None:
    """Take an exam one question at a time; answers are saved as you go."""
    try:
        taker = ExamTaker(file)
    except ExamFileError as exc:
        raise typer.BadParameter(str(exc)) from exc
    total = len(taker.questions)
    verb = "Resuming" if taker.resumed else "Starting"
    console.print(f"{verb} attempt {taker.attempt['attempt']} of {taker.exam['exam']}. {TAKE_HELP}")
    while (question := taker.current()) is not None:
        _show(question, total)
        reply = _read_answer(question)
        if reply is None or reply == "/quit":
            console.print(f"Saved. Run `brightlearn exam take {file}` to resume.")
            return
        if reply == "/skip":
            taker.skip()
            continue
        if reply == "/help":
            console.print(TAKE_HELP)
            continue
        try:
            taker.answer(reply)
        except ValueError as exc:
            console.print(f"[yellow]{exc}[/]")
    taker.finish()
    console.print(f"All answered. Grade it with `brightlearn exam grade {file}`.")


def _show(question: dict, total: int) -> None:
    label = question["format"].replace("_", " ")
    console.print(
        f"\n[bold]Question {question['index'] + 1}/{total}[/] · {label} · {question['difficulty']}"
    )
    console.print(escape(question["stem"]))
    for letter, option in zip(LETTERS, question.get("options") or [], strict=False):
        console.print(f"  {letter}. {escape(option)}")


def _read_answer(question: dict) -> str | None:
    """One line, or for coding every line up to /done. None on end of input."""
    try:
        first = console.input("[bold]answer>[/] ")
        if question["format"] != "coding" or first.strip().startswith("/"):
            return first.strip()
        lines = [first]
        while (line := console.input("")).strip() != "/done":
            lines.append(line)
        return "\n".join(lines).strip()
    except (EOFError, KeyboardInterrupt):
        return None


@app.command("grade")
def grade(
    file: Path = typer.Argument(..., exists=True, dir_okay=False, help="The exam's .json."),
) -> None:
    """Grade the latest attempt: evidence per question, mastery through the Analyzer's rule."""
    config = load_config()
    conn = connect(config.db_path)
    try:
        providers = common.model_providers(config, ("analysis",))
        grader = ExamGrader(
            LearnerMemory(conn), common.router(config, conn, providers), ChallengeStore(conn)
        )
        try:
            report = grader.grade(file)
        except (GradeError, ExamFileError) as exc:
            console.print(f"[red]{escape(str(exc))}[/]")
            raise typer.Exit(1) from exc
    finally:
        conn.close()

    table = Table("Concept", "Score", "Level", title=f"{report.exam_id} · attempt {report.attempt}")
    for s in report.scores:
        level = "" if s.level_before is None else f"{s.level_before} → {s.level_after}"
        table.add_row(escape(s.name), f"{s.correct}/{s.total}", level)
    console.print(table)
    console.print(
        f"Score {report.correct}/{report.graded} graded"
        + (f", {report.unanswered} skipped" if report.unanswered else "")
        + f". {len(report.new_evidence)} new evidence row(s)"
        + (
            f"; {report.already_graded} answer(s) were already graded"
            if report.already_graded
            else ""
        )
        + "."
    )
    if report.queued_challenges:
        console.print(f"{report.queued_challenges} challenge(s) queued for the next tutor session.")
    if report.ungraded:
        detail = f": {escape(report.grader_error)}" if report.grader_error else ""
        console.print(
            f"[yellow]{len(report.ungraded)} answer(s) not graded yet{detail}. "
            "Run grade again to retry them.[/]"
        )
